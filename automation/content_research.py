"""投稿前に実行するリサーチエージェント。

閲覧数・エンゲージメントを稼いでいるAI活用系の発信アカウントが、
今どんな切り口・フォーマットで投稿しているかをweb_searchで調べ、
一般的な傾向として要約する。特定アカウントの丸写し・転載はしない。
"""

from common import generate_with_search

RESEARCH_PROMPT = """あなたはSNSマーケティングのリサーチャーです。

web_searchを使って、X(Twitter)やThreadsで生成AI・ChatGPT・Claude・業務効率化AI活用について
発信し、閲覧数やエンゲージメントを稼いでいるアカウント・投稿の「傾向」を調査してください。

# 調査観点
- どんな切り口・フォーマットの投稿が伸びているか、幅広く調べること
  (例:プロンプト集、ビフォーアフター比較、業務効率化の実例、AIで稼ぐ・マネタイズ系、ツール比較、
  失敗談、時事ネタとの絡めなど。これらはあくまで例なので、他に伸びている切り口があればそれも拾うこと)
- スレッド投稿で、1投稿目・2投稿目がどう工夫されていて読者に「続きを読みたい」と思わせているか
  (フックの型、引きの作り方)

# 出力ルール
- 特定の個人名・アカウント名・投稿を名指しで引用・転載しないこと。あくまで一般的な傾向として書く
- 実在しないフォロワー数・閲覧数などの具体的な数字を捏造しないこと
- 日本語で、3〜6個の箇条書き。合計400字程度まで
"""


def research_trending_ai_content() -> str:
    """人気AI発信アカウントの投稿傾向をリサーチするエージェント。"""
    return generate_with_search(RESEARCH_PROMPT, max_tokens=1200)
